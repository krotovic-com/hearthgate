// Drives the dashboard for scripts/site-screenshots/run.sh: node shots.js SETUP-CODE OUT-DIR
const { chromium } = require('playwright');
const CODE = process.argv[2], BASE = 'https://127.0.0.1:7380', OUT = process.argv[3];
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ ignoreHTTPSErrors: true, viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2, colorScheme: 'light' });
  const page = await ctx.newPage();
  await page.goto(BASE);
  await page.getByLabel('Setup code').fill(CODE);
  await page.getByLabel('Username').fill('lukas');
  await page.getByLabel('Password', { exact: true }).fill('correct horse battery staple');
  await page.getByLabel('Repeat password').fill('correct horse battery staple');
  await page.getByRole('button', { name: 'Create account' }).click();
  await page.getByRole('heading', { name: 'Overview', level: 1 }).waitFor();
  await page.waitForTimeout(6000);
  await page.getByRole('link', { name: 'Services', exact: true }).click();
  await page.waitForTimeout(1000);
  await page.keyboard.press('Control+j');
  const panel = page.getByRole('complementary', { name: 'Ask AI' });
  await panel.waitFor();
  await panel.getByLabel('Message Ask AI').fill('Publish Immich at photos.example.com. It runs on this machine on port 2283.');
  await panel.getByLabel('Message Ask AI').press('Enter');
  await panel.getByText('0 of 4 done').waitFor();
  await page.waitForTimeout(500);
  await page.screenshot({ path: OUT + '/ask-ai-plan.png' });
  await panel.getByRole('button', { name: 'Apply' }).click();
  await panel.getByText(/Applied · revision \d+/).waitFor();
  await page.waitForTimeout(6000);
  await page.getByRole('link', { name: 'Public interfaces', exact: true }).click();
  await page.waitForTimeout(800);
  await panel.getByLabel('Message Ask AI').fill("Done. What's next?");
  await panel.getByLabel('Message Ask AI').press('Enter');
  await panel.getByText('1 of 4 done').waitFor();
  await page.waitForTimeout(500);
  await page.screenshot({ path: OUT + '/ask-ai-step2.png' });
  await panel.getByRole('button', { name: 'Close Ask AI' }).click();
  await page.getByRole('link', { name: 'AI review', exact: true }).click();
  await page.getByRole('button', { name: 'Run review now' }).click();
  await page.getByRole('heading', { name: 'The firewall is off' }).waitFor();
  await page.waitForTimeout(500);
  await page.screenshot({ path: OUT + '/ai-review.png' });
  await b.close();
})().catch((e) => { console.error(e); process.exit(1); });
